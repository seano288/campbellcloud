//
// - Build the Train: 3 to 6 words, no floating words, and exactly one order of its cars that makes sense (the test runs the order
//   checker in grammar.ts over every one). 3 words is Level 1, 4 to 5 Level 2, 5 to 6 and the questions Level 3.
// - Engine and Caboose: every sentence.
// - What Happened: the ones with a meaning (`m`) that can be drawn.
// - Who, What, Where: the ones with questions (`ask`), each answered by the picture of who, where, what it has or what it does.
// - Fix the Train: the Build the Train ones, so a swapped pair never makes another sentence.
//
// `noOrder` marks a sentence the checker found a second sensible order for (kept for the other kinds): the trap list in the test
// keeps the reasons.
